package com.sharan.deskcharm.charm;

/**
 * The built-in original shape families a {@link Charm} can render as, when it
 * has no custom imported image. All shapes are original geometry drawn by
 * {@code CharmRenderer} in the rendering package — none of Hangly's artwork.
 */
public enum CharmType {
    ROUNDED_DIAMOND,
    STAR,
    CIRCLE_PENDANT,
    CRESCENT,
    LEAF,
    CUSTOM_IMAGE
}
